#!/usr/bin/env python3
"""Generate src/c/glyphs.c from the pixel art below.

Usage: python3 tools/gen_glyphs.py src/c/glyphs.c [preview.png]

Each glyph is hand-drawn for its exact size ('#' = ink). The 9 px planet
symbols and 5x7 status icons are the original Ecliptic artwork; the larger
sets are redrawn for bigger displays, not scaled.
"""
import sys

GLYPHS = {}


def glyph(name, art):
    rows = [r for r in art.strip('\n').split('\n')]
    w = len(rows[0])
    assert all(len(r) == w for r in rows), name
    GLYPHS[name] = (w, rows)


