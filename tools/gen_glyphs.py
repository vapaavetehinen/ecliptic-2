out = ['// Generated by tools/gen_glyphs.py. Edit the pixel art there, not here.',
       '#include "glyphs.h"', '']
for name, (w, rows) in GLYPHS.items():
    out.append('static const uint16_t %s_ROWS[] = {' % name)
    for r in rows:
        out.append('  0x%04x,  // %s' % (int(r.replace('.', '0').replace('#', '1'), 2), r))
    out.append('};')
    out.append('const Glyph GLYPH_%s = {%s_ROWS, %d, %d};' % (name, name, w, len(rows)))
    out.append('')
open(sys.argv[1], 'w').write('\n'.join(out))

if len(sys.argv) > 2:
    from PIL import Image
    scale, pad = 12, 2
    names = list(GLYPHS)
    W = sum(GLYPHS[n][0] + pad for n in names) + pad
    H = max(len(GLYPHS[n][1]) for n in names) + 2 * pad
    im = Image.new('RGB', (W, H), (90, 90, 90))
    x = pad
    for n in names:
        w, rows = GLYPHS[n]
        for j, r in enumerate(rows):
            for i, ch in enumerate(r):
                im.putpixel((x + i, pad + j), (0, 0, 0) if ch == '#' else (255, 255, 255))
        x += w + pad
    im.resize((W * scale, H * scale), Image.NEAREST).save(sys.argv[2])
