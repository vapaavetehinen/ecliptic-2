#!/usr/bin/env python3
"""Generate src/c/stars_data.c from the original Ecliptic stars.c.

Usage: python3 tools/gen_stars.py ../ecliptic-pebble/src/c/stars.c src/c/stars_data.c

Coordinates are stored as fixed point (degrees x 100). Star colour is
precomputed with the same magnitude / colour-index rules as the original.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8', errors='replace').read()
num = r'\s*(-?\d+(?:\.\d+)?)\s*'

lines = re.findall(r'draw_const_line\(ctx,\s*sunL,%s,%s,%s,%s\)' % (num, num, num, num), text)
stars = re.findall(r'draw_star\(ctx,\s*sunL,%s,%s,%s,%s\)' % (num, num, num, num), text)


def fx(v):
    return int(round(float(v) * 100))


def colour_class(mag, ci):
    # Mirrors draw_star() in the original.
    c = 0  # white
    if 2.3 < mag <= 3.5:
        c = 1  # light gray
    if mag > 3.5:
        c = 2  # dark gray
    if mag <= 2.3:
        if ci > 1:
            c = 3  # orange
        if 0.5 < ci <= 1:
            c = 4  # rajah
        if ci < 0:
            c = 5  # electric blue
    return c


out = ['// Generated by tools/gen_stars.py from the original Ecliptic stars.c. Do not edit.',
       '#include "stars_data.h"', '',
       'const ConstLine CONST_LINES[] = {']
for a, b, c, d in lines:
    out.append('  {%d, %d, %d, %d},' % (fx(a), fx(b), fx(c), fx(d)))
out += ['};', 'const uint16_t CONST_LINE_COUNT = %d;' % len(lines), '',
        '#ifdef PBL_COLOR', 'const Star STARS[] = {']
for lat, lon, mag, ci in stars:
    m = float(mag)
    out.append('  {%d, %d, %d, %d},' % (fx(lat), fx(lon), int(round(m * 10)), colour_class(m, float(ci))))
out += ['};', 'const uint16_t STAR_COUNT = %d;' % len(stars), '#endif', '']
open(dst, 'w').write('\n'.join(out))
print('%d lines, %d stars' % (len(lines), len(stars)))
